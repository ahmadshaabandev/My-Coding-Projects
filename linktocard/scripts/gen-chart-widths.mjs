#!/usr/bin/env node
// Generates src/charts/inter-widths.ts: the advance width of every character in the bundled Inter
// subsets (Latin, Latin Extended, Cyrillic, Greek, Vietnamese) at weights 400 and 600.
// The chart layout uses it to measure text without running the text engine.
//
//   node scripts/gen-chart-widths.mjs
//
// Re-run it when the font files under src/render/fonts change. Dev-time only: it reads the
// WOFF files with node:zlib; nothing here is part of the Worker.
import { readFileSync, writeFileSync } from 'node:fs'
import { inflateSync } from 'node:zlib'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const fontDir = path.resolve(here, '../src/render/fonts')
const SUBSETS = ['latin', 'latin-ext', 'cyrillic', 'greek', 'vietnamese']
const WEIGHTS = [400, 600]

/** WOFF 1.0 container -> { tag: Buffer } (tables are zlib-compressed one by one). */
function woffTables(file) {
  const woff = readFileSync(file)
  if (woff.toString('latin1', 0, 4) !== 'wOFF') throw new Error(`${file} is not a WOFF 1.0 file`)
  const tables = {}
  for (let i = 0; i < woff.readUInt16BE(12); i++) {
    const entry = 44 + i * 20
    const offset = woff.readUInt32BE(entry + 4)
    const compLength = woff.readUInt32BE(entry + 8)
    const origLength = woff.readUInt32BE(entry + 12)
    const raw = woff.subarray(offset, offset + compLength)
    tables[woff.toString('latin1', entry, entry + 4)] = compLength < origLength ? inflateSync(raw) : raw
  }
  return tables
}

/** code point -> glyph id, from the cmap subtables of format 4 and 12. */
function readCmap(cmap) {
  const map = new Map()
  for (let i = 0; i < cmap.readUInt16BE(2); i++) {
    const sub = cmap.readUInt32BE(4 + i * 8 + 4)
    const format = cmap.readUInt16BE(sub)
    if (format === 4) {
      const segCount = cmap.readUInt16BE(sub + 6) / 2
      const ends = sub + 14
      const starts = ends + segCount * 2 + 2
      const deltas = starts + segCount * 2
      const offsets = deltas + segCount * 2
      for (let s = 0; s < segCount; s++) {
        const end = cmap.readUInt16BE(ends + s * 2)
        const start = cmap.readUInt16BE(starts + s * 2)
        const delta = cmap.readInt16BE(deltas + s * 2)
        const rangeOffset = cmap.readUInt16BE(offsets + s * 2)
        for (let c = start; c <= end && c !== 0xffff; c++) {
          let glyph
          if (rangeOffset === 0) glyph = (c + delta) & 0xffff
          else {
            glyph = cmap.readUInt16BE(offsets + s * 2 + rangeOffset + (c - start) * 2)
            if (glyph !== 0) glyph = (glyph + delta) & 0xffff
          }
          if (glyph !== 0) map.set(c, glyph)
        }
      }
    } else if (format === 12) {
      for (let g = 0; g < cmap.readUInt32BE(sub + 12); g++) {
        const at = sub + 16 + g * 12
        const start = cmap.readUInt32BE(at)
        const end = cmap.readUInt32BE(at + 4)
        const glyph = cmap.readUInt32BE(at + 8)
        for (let c = start; c <= end; c++) map.set(c, glyph + (c - start))
      }
    }
  }
  return map
}

/** code point -> advance width in 1/1000 em. */
function advances(file) {
  const { head, hhea, hmtx, cmap } = woffTables(file)
  const unitsPerEm = head.readUInt16BE(18)
  const metrics = hhea.readUInt16BE(34)
  const out = new Map()
  for (const [code, glyph] of readCmap(cmap)) {
    const units = hmtx.readUInt16BE(Math.min(glyph, metrics - 1) * 4)
    out.set(code, Math.round((units / unitsPerEm) * 1000))
  }
  return out
}

/** Runs of consecutive code points: [first code point, width, width, ...]. */
function runs(widths) {
  const codes = [...widths.keys()].filter((code) => code >= 0x20).sort((a, b) => a - b)
  const out = []
  let run
  for (const code of codes) {
    if (!run || code !== run[0] + run.length - 1) out.push((run = [code]))
    run.push(widths.get(code))
  }
  return out
}

const lines = []
let total = 0
for (const weight of WEIGHTS) {
  const widths = new Map()
  // Same order as the fallback stack: the first subset that has a character wins.
  for (const subset of SUBSETS) {
    for (const [code, width] of advances(path.join(fontDir, `inter-${subset}-${weight}-normal.woff`))) {
      if (!widths.has(code)) widths.set(code, width)
    }
  }
  total += widths.size
  lines.push(`  ${weight}: ${JSON.stringify(runs(widths))},`)
}

const source = `// GENERATED by scripts/gen-chart-widths.mjs from src/render/fonts/inter-*-{400,600}-normal.woff. Do not edit.
// To regenerate (after the font files change): node scripts/gen-chart-widths.mjs
// Advance widths in 1/1000 em, as runs of consecutive code points: [first code point, width, width, ...].
export const INTER_WIDTHS: Record<400 | 600, number[][]> = {
${lines.join('\n')}
}
`
const target = path.resolve(here, '../src/charts/inter-widths.ts')
writeFileSync(target, source)
console.log(`${path.relative(process.cwd(), target)}: ${total} widths, ${source.length} bytes`)
