#!/usr/bin/env python3
"""Write requirements.lock and requirements-runtime.lock: every package, pinned and hashed.

    .venv/bin/python scripts/lock_requirements.py            # write both lock files
    .venv/bin/python scripts/lock_requirements.py --check    # exit 1 if one is out of date

requirements.lock holds everything requirements.txt asks for (the development and test
environment). requirements-runtime.lock holds the same pins and hashes for the app alone:
the requirements marked "# tests only" in requirements.txt, and whatever only they need,
are left out. The container image (Dockerfile) installs that one, so no test tool is in
the image.

Run it with the project's virtual environment after changing requirements.txt and
installing it: the versions are the ones installed there (the ones tested), for the
direct requirements of requirements.txt and everything they need (markers evaluated
for this Python, no extras). The sha256 of every file PyPI holds for each of those
versions is fetched from https://pypi.org/pypi/<name>/<version>/json, so the lock
installs on any platform with:

    pip install --require-hashes -r requirements.lock

This is a development tool: it is the only script that goes to the network, and the
app itself never runs it.
"""

from __future__ import annotations

import argparse
import importlib.metadata as md
import json
import sys
import urllib.request
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parent.parent
REQUIREMENTS = ROOT / "requirements.txt"
LOCK = ROOT / "requirements.lock"
RUNTIME_LOCK = ROOT / "requirements-runtime.lock"
#: A requirements.txt line whose comment starts with this is not in RUNTIME_LOCK.
TESTS_ONLY = "tests only"

HEADER = """\
# Mommy prototype: every package, pinned to the version installed and tested, with the
# sha256 of each file PyPI holds for it. Generated by scripts/lock_requirements.py from
# requirements.txt; do not edit by hand. Install with:
#   python3 -m venv .venv && .venv/bin/pip install --require-hashes -r requirements.lock
"""

RUNTIME_HEADER = """\
# Mommy prototype, the app alone (what the container image installs): the pins and hashes
# of requirements.lock without the requirements marked "tests only" in requirements.txt
# and what only they need. Generated by scripts/lock_requirements.py; do not edit by hand.
# Install with: pip install --require-hashes --only-binary=:all: -r requirements-runtime.lock
"""


def direct_requirements(*, runtime_only: bool = False) -> list[Requirement]:
    """The requirements of requirements.txt; with ``runtime_only``, without those marked
    "# tests only"."""
    out = []
    for line in REQUIREMENTS.read_text(encoding="utf-8").splitlines():
        spec, _, comment = line.partition("#")
        spec = spec.strip()
        if not spec or (runtime_only and comment.strip().startswith(TESTS_ONLY)):
            continue
        out.append(Requirement(spec))
    return out


def closure(direct: list[Requirement]) -> dict[str, str]:
    """``{canonical name: installed version}`` of the requirements and their dependencies."""
    found: dict[str, str] = {}
    stack = [r.name for r in direct]
    while stack:
        name = canonicalize_name(stack.pop())
        if name in found:
            continue
        dist = md.distribution(name)
        found[name] = dist.version
        for spec in dist.requires or []:
            req = Requirement(spec)
            if req.marker is None or req.marker.evaluate({"extra": ""}):
                stack.append(req.name)
    for req in direct:
        installed = found[canonicalize_name(req.name)]
        if not req.specifier.contains(installed, prereleases=True):
            raise SystemExit(f"{req.name} {installed} is installed, but requirements.txt asks for {req.specifier}")
    return found


def hashes(name: str, version: str) -> list[str]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=30) as response:  # noqa: S310 - fixed https URL
        data = json.load(response)
    digests = sorted({f["digests"]["sha256"] for f in data["urls"] if f.get("digests", {}).get("sha256")})
    if not digests:
        raise SystemExit(f"PyPI lists no files for {name} {version}")
    return digests


def render(versions: dict[str, str], header: str = HEADER, digests: dict[str, list[str]] | None = None) -> str:
    """The lock file text for ``versions``; ``digests`` caches the hashes by name."""
    digests = {} if digests is None else digests
    lines = [header]
    for name in sorted(versions):
        version = versions[name]
        if name not in digests:
            digests[name] = hashes(name, version)
        entry = [f"{name}=={version}"] + [f"--hash=sha256:{h}" for h in digests[name]]
        lines.append(" \\\n    ".join(entry))
    return "\n".join(lines) + "\n"


def runtime_versions(versions: dict[str, str]) -> dict[str, str]:
    """The part of ``versions`` the app needs without the "tests only" requirements."""
    runtime = closure(direct_requirements(runtime_only=True))
    assert set(runtime) <= set(versions)
    return {name: versions[name] for name in runtime}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="only check that requirements.lock is up to date")
    args = parser.parse_args()
    versions = closure(direct_requirements())
    digests: dict[str, list[str]] = {}
    texts = {
        LOCK: render(versions, HEADER, digests),
        RUNTIME_LOCK: render(runtime_versions(versions), RUNTIME_HEADER, digests),
    }
    if args.check:
        stale = [path.name for path, text in texts.items()
                 if (path.read_text(encoding="utf-8") if path.exists() else "") != text]
        if stale:
            print(f"{', '.join(stale)} out of date: run scripts/lock_requirements.py", file=sys.stderr)
            return 1
        print("requirements.lock and requirements-runtime.lock are up to date")
        return 0
    for path, text in texts.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
